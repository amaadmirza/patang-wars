#!/usr/bin/env node
/* After `cap add android` / `cap add ios`: the game's own settings for the native projects.
 *   - landscape only (Patang Wars is played sideways), full screen (no status / navigation bar)
 *   - Android: vibration permission, immersive full screen, version from APP_VERSION / APP_BUILD
 *   - iPhone/iPad: landscape orientations, status bar hidden, full screen, version numbers
 * Every change is checked: if a template ever changes so a patch can't find its place, the build stops with the reason
 * instead of quietly making an app that turns upright.  Usage: node scripts/patch-native.js [android] [ios] */
'use strict';
const fs = require('fs'), path = require('path');
const APP = path.join(__dirname, '..');
const cfg = JSON.parse(fs.readFileSync(path.join(APP, 'capacitor.config.json'), 'utf8'));
const VERSION = process.env.APP_VERSION || require(path.join(APP, 'package.json')).version;   // shown to players, e.g. 1.6.4
const BUILD = String(parseInt(process.env.APP_BUILD || '1', 10) || 1);                          // must go up with every release
const which = process.argv.slice(2); const want = p => !which.length || which.includes(p);
const fail = m => { console.error('patch-native: ' + m); process.exit(1); };
const edit = (file, fn) => { if (!fs.existsSync(file)) fail('missing ' + path.relative(APP, file)); const a = fs.readFileSync(file, 'utf8'), b = fn(a); if (b !== a) fs.writeFileSync(file, b); console.log('  patched ' + path.relative(APP, file)); };

if (want('android') && fs.existsSync(path.join(APP, 'android'))) {
  console.log('android');
  const man = path.join(APP, 'android', 'app', 'src', 'main', 'AndroidManifest.xml');
  edit(man, s => {
    if (!/android:name="\.MainActivity"/.test(s)) fail('MainActivity not found in AndroidManifest.xml');
    if (!/android:screenOrientation=/.test(s)) s = s.replace(/android:name="\.MainActivity"/, 'android:name=".MainActivity"\n            android:screenOrientation="sensorLandscape"');
    if (!/android\.permission\.VIBRATE/.test(s)) s = s.replace(/<\/manifest>\s*$/, '    <uses-permission android:name="android.permission.VIBRATE" />\n</manifest>\n');
    if (!/sensorLandscape/.test(s) || !/VIBRATE/.test(s)) fail('AndroidManifest.xml patch did not apply');
    return s;
  });
  // immersive full screen: the game uses every pixel, the system bars come back with a swipe and hide again
  const pkg = cfg.appId.split('.'), dir = path.join(APP, 'android', 'app', 'src', 'main', 'java', ...pkg);
  const javaFile = path.join(dir, 'MainActivity.java'), ktFile = path.join(dir, 'MainActivity.kt');
  if (fs.existsSync(ktFile)) fs.unlinkSync(ktFile);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(javaFile, `package ${cfg.appId};

import android.os.Bundle;
import android.view.WindowManager;
import androidx.core.view.WindowCompat;
import androidx.core.view.WindowInsetsCompat;
import androidx.core.view.WindowInsetsControllerCompat;
import com.getcapacitor.BridgeActivity;

/** Patang Wars: landscape, full screen, screen kept on while the app is open (generated by scripts/patch-native.js) */
public class MainActivity extends BridgeActivity {
  @Override
  public void onCreate(Bundle savedInstanceState) {
    super.onCreate(savedInstanceState);
    getWindow().addFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON);
    hideBars();
  }

  @Override
  public void onWindowFocusChanged(boolean hasFocus) {
    super.onWindowFocusChanged(hasFocus);
    if (hasFocus) hideBars();
  }

  private void hideBars() {
    WindowCompat.setDecorFitsSystemWindows(getWindow(), false);
    WindowInsetsControllerCompat c = WindowCompat.getInsetsController(getWindow(), getWindow().getDecorView());
    c.hide(WindowInsetsCompat.Type.systemBars());
    c.setSystemBarsBehavior(WindowInsetsControllerCompat.BEHAVIOR_SHOW_TRANSIENT_BARS_BY_SWIPE);
  }
}
`);
  console.log('  wrote ' + path.relative(APP, javaFile));
  const gradle = path.join(APP, 'android', 'app', 'build.gradle');
  edit(gradle, s => {
    if (!/versionCode\s+\d+/.test(s) || !/versionName\s+"[^"]*"/.test(s)) fail('versionCode/versionName not found in app/build.gradle');
    return s.replace(/versionCode\s+\d+/, 'versionCode ' + BUILD).replace(/versionName\s+"[^"]*"/, `versionName "${VERSION}"`);
  });
}

if (want('ios') && fs.existsSync(path.join(APP, 'ios'))) {
  console.log('ios');
  const plist = path.join(APP, 'ios', 'App', 'App', 'Info.plist');
  edit(plist, s => {
    const LAND = '<array>\n\t\t<string>UIInterfaceOrientationLandscapeLeft</string>\n\t\t<string>UIInterfaceOrientationLandscapeRight</string>\n\t</array>';
    const setKey = (src, key, valueXml) => {
      const re = new RegExp(`<key>${key}</key>\\s*(<array>[\\s\\S]*?</array>|<true/>|<false/>|<string>[^<]*</string>)`);
      return re.test(src) ? src.replace(re, `<key>${key}</key>\n\t${valueXml}`) : src.replace(/<\/dict>\s*<\/plist>\s*$/, `\t<key>${key}</key>\n\t${valueXml}\n</dict>\n</plist>\n`);
    };
    s = setKey(s, 'UISupportedInterfaceOrientations', LAND);
    s = setKey(s, 'UISupportedInterfaceOrientations~ipad', LAND);
    s = setKey(s, 'UIStatusBarHidden', '<true/>');
    s = setKey(s, 'UIViewControllerBasedStatusBarAppearance', '<false/>');
    s = setKey(s, 'UIRequiresFullScreen', '<true/>');
    s = setKey(s, 'CFBundleShortVersionString', `<string>${VERSION}</string>`);
    s = setKey(s, 'CFBundleVersion', `<string>${BUILD}</string>`);
    s = setKey(s, 'ITSAppUsesNonExemptEncryption', '<false/>');   // no custom encryption: skips a question at every App Store upload
    if (/UIInterfaceOrientationPortrait</.test(s) || !/UIRequiresFullScreen<\/key>\s*<true\/>/.test(s)) fail('Info.plist patch did not apply');
    return s;
  });
  // the Xcode project also carries the version numbers (MARKETING_VERSION / CURRENT_PROJECT_VERSION)
  const pbx = path.join(APP, 'ios', 'App', 'App.xcodeproj', 'project.pbxproj');
  if (fs.existsSync(pbx)) edit(pbx, s => s.replace(/MARKETING_VERSION = [^;]+;/g, `MARKETING_VERSION = ${VERSION};`).replace(/CURRENT_PROJECT_VERSION = [^;]+;/g, `CURRENT_PROJECT_VERSION = ${BUILD};`));
}
console.log(`version ${VERSION} (build ${BUILD})`);
