// Scans assets/spools/*.png and writes src/spools.js:  node tools/build-spools.js
// Reels are cosmetic only (the thread choice decides cutting/strength).
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), dir = path.join(root, 'assets', 'spools');
// Skipped on purpose: a file named after another company's game, and two named after Nestle products
// (Nescau, Ninho) that likely show their packaging. Remove a name from here if you have checked the art is fine.
const SKIP = /^(pipacombate|nescau|ninho)$/i;
const out = fs.readdirSync(dir)
  .filter(f => /\.png$/i.test(f))
  .map(f => f.replace(/\.png$/i, ''))
  .filter(id => !SKIP.test(id))
  .map(id => ({ id: 'spool:' + id, name: id.replace(/([a-z])([A-Z0-9])/g, '$1 $2').replace(/^./, c => c.toUpperCase()), src: 'assets/spools/' + id + '.png' }))
  .sort((a, b) => a.name.localeCompare(b.name, undefined, { numeric: true }));
fs.writeFileSync(path.join(root, 'src', 'spools.js'), '/* generated by tools/build-spools.js */\nwindow.SPOOL_CATALOG = ' + JSON.stringify(out, null, 1) + ';\n');
console.log(out.length + ' spools');
