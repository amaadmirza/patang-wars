// Scans assets/kites/<folder>/*.png and writes src/catalog.js: node tools/build-catalog.js
// v6.3: every kite has a proper name and lives in the folder of its kind. The FOLDER decides how it flies (the physics
// archetype in src/data.js); the name comes from tools/kite-names.json (or, for a new picture you drop in, from its
// file name: "lal-baaz.png" -> "Lal Baaz").
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), dir = path.join(root, 'assets', 'kites');
const FOLDER_ARCHE = { patang: 'patang', tukkal: 'tukkal', pipa: 'pipa', raia: 'delta', dabba: 'eddy', parinda: 'bird', sitara: 'rokkaku' };
const MINI = new Set(['gudiya-gulabi', 'gudiya-neeli']);   // small kites: drawn and flown at 70%
const slug = s => s.toLowerCase().normalize('NFKD').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const NAMES = {};
try { for (const [k, v] of Object.entries(JSON.parse(fs.readFileSync(path.join(__dirname, 'kite-names.json'), 'utf8')))) if (Array.isArray(v) && typeof v[1] === 'string') NAMES[slug(v[1])] = v[1]; } catch (e) {}
const titled = id => id.split('-').map((w, i) => i && ['ka', 'ki', 'ke'].includes(w) ? w : w.charAt(0).toUpperCase() + w.slice(1)).join(' ');

const out = [], seen = new Set();
for (const folder of fs.readdirSync(dir, { withFileTypes: true })) {
  if (!folder.isDirectory()) continue;
  const arche = FOLDER_ARCHE[folder.name.toLowerCase()];
  if (!arche) { console.warn(`skipped folder assets/kites/${folder.name} (use one of: ${Object.keys(FOLDER_ARCHE).join(', ')})`); continue; }
  for (const f of fs.readdirSync(path.join(dir, folder.name)).sort()) {
    if (!/\.png$/i.test(f)) continue;
    const id = slug(f.replace(/\.png$/i, ''));
    if (seen.has(id)) { console.warn('duplicate kite name skipped: ' + folder.name + '/' + f); continue; }
    seen.add(id);
    out.push({ id: 'png:' + id, name: NAMES[id] || titled(id), src: `assets/kites/${folder.name}/${f}`, arche, scale: MINI.has(id) ? 0.7 : 1 });
  }
}
out.sort((a, b) => a.name.localeCompare(b.name, undefined, { numeric: true }));
fs.writeFileSync(path.join(root, 'src', 'catalog.js'), '/* generated by tools/build-catalog.js */\nwindow.KITE_CATALOG = ' + JSON.stringify(out, null, 1) + ';\n');
console.log(out.length + ' kites');
